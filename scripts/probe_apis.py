"""Throwaway probe: ONE real call each to TypeSafe and Senso. Never prints a key.

Run on a machine that has .env (not in the cloud):
    python scripts/probe_apis.py                 # prints what worked
    python scripts/probe_apis.py --write-notes   # also writes docs/API_NOTES.md from calls that succeeded

API_NOTES.md only records request shapes from calls that really succeeded. Anything taken from the
docs but not confirmed by a call is marked "docs only, not verified".
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app import config  # noqa: E402  (loads .env without overriding real env vars)

TYPESAFE_URL = "https://api.typesafe.ai/v1/systemone"
TYPESAFE_BODY = {
    "model": "jev-latest",
    "state": {"offer": {"price": 58, "terms_text": "$58/mo for 3 months, then $95/mo"}},
    "questions": {
        "raises_price_after_intro": {
            "type": "noul",
            "instructions": "Does `offer` raise the price after an introductory period?",
        }
    },
}
SENSO_BODY = {"query": "introductory rate reverts to standard price", "max_results": 3, "search_type": "hybrid"}


def fail_reason(resp: httpx.Response) -> str:
    try:
        data = resp.json()
        msg = data.get("error") or data.get("message") or data.get("detail") or ""
    except Exception:
        msg = ""
    return f"HTTP {resp.status_code} {str(msg)[:200]}".strip()


def probe_typesafe() -> dict:
    if not config.TYPESAFE_API_KEY:
        return {"ok": False, "why": "TYPESAFE_API_KEY is missing"}
    r = httpx.post(TYPESAFE_URL, json=TYPESAFE_BODY, timeout=30,
                   headers={"Authorization": f"Bearer {config.TYPESAFE_API_KEY}"})
    if r.status_code != 200:
        return {"ok": False, "why": fail_reason(r)}
    data = r.json()
    answer = (data.get("answers") or {}).get("raises_price_after_intro") or {}
    return {"ok": "noul" in answer, "why": "" if "noul" in answer else "no answers.<id>.noul in response",
            "top_keys": sorted(data), "answer_keys": sorted(answer), "p": answer.get("noul")}


def probe_senso() -> dict:
    if not config.SENSO_API_KEY:
        return {"ok": False, "why": "SENSO_API_KEY is missing"}
    url = f"{config.SENSO_BASE_URL.rstrip('/')}/org/search/context"
    r = httpx.post(url, json=SENSO_BODY, timeout=30, headers={"X-API-Key": config.SENSO_API_KEY})
    if r.status_code != 200:
        return {"ok": False, "why": fail_reason(r)}
    data = r.json()
    results = data.get("results") or []
    return {"ok": True, "why": "" if results else "call worked but returned no results (is the knowledge base empty?)",
            "top_keys": sorted(data), "result_keys": sorted(results[0]) if results else [], "results": results[:3],
            "url_path": "/org/search/context"}


def show(ts: dict, se: dict) -> None:
    print("TypeSafe  POST", TYPESAFE_URL)
    print("  auth: Authorization: Bearer <TYPESAFE_API_KEY>")
    print("  body:", json.dumps(TYPESAFE_BODY))
    if ts["ok"]:
        print("  response top-level keys:", ts["top_keys"], "| answer keys:", ts["answer_keys"])
        print("  probability (answers.raises_price_after_intro.noul):", ts["p"])
    else:
        print("  FAILED:", ts["why"])
    print("\nSenso  POST {SENSO_BASE_URL}/org/search/context")
    print("  auth: X-API-Key: <SENSO_API_KEY>")
    print("  body:", json.dumps(SENSO_BODY))
    if se["ok"]:
        print("  response top-level keys:", se["top_keys"], "| result keys:", se["result_keys"])
        for x in se["results"]:
            print("  -", x.get("content_id"), x.get("version_id"), x.get("score"), "|",
                  (x.get("chunk_text") or "")[:120].replace("\n", " "))
        if se["why"]:
            print("  NOTE:", se["why"])
    else:
        print("  FAILED:", se["why"])


def write_notes(ts: dict, se: dict) -> None:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [f"# API notes (generated by scripts/probe_apis.py, {now})", "",
           "Only sections marked VERIFIED come from a real call that succeeded. No keys or document text are recorded here.", ""]
    out += ["## TypeSafe: " + ("VERIFIED by a real call" if ts["ok"] else "NOT VERIFIED (" + ts["why"] + ")"), "",
            f"- `POST {TYPESAFE_URL}`, header `Authorization: Bearer $TYPESAFE_API_KEY`, `Content-Type: application/json`",
            "- Request body (several Nouls = several keys under `questions`; they run in parallel; the keys are yours to name):",
            "```json", json.dumps(TYPESAFE_BODY, indent=2), "```",
            "- Probability for question `<id>` is `answers.<id>.noul`, a number from 0 to 1 (chance of yes).",
            "- Model name `jev-latest` is from the docs; `GET /v1/models` lists others (docs only, not verified).", ""]
    if ts["ok"]:
        out += [f"- Verified response top-level keys: {ts['top_keys']}; answer keys: {ts['answer_keys']}", ""]
    out += ["## Senso context search: " + ("VERIFIED by a real call" if se["ok"] else "NOT VERIFIED (" + se["why"] + ")"), "",
            "- `POST {SENSO_BASE_URL}/org/search/context`, header `X-API-Key: $SENSO_API_KEY`. Default base `https://apiv2.senso.ai/api/v1`.",
            "- Request body (`query` required; `max_results` default 5, max 20; `search_type` hybrid|lexical|vector):",
            "```json", json.dumps(SENSO_BODY, indent=2), "```",
            "- Results are under `results`, each with `content_id`, `version_id`, `chunk_text`, `score`, `rank` (docs; the keys seen in the real call are listed below).", ""]
    if se["ok"]:
        out += [f"- Verified response top-level keys: {se['top_keys']}; result keys: {se['result_keys']}"]
        if se["why"]:
            out += [f"- NOTE: {se['why']}"]
    (ROOT / "docs" / "API_NOTES.md").write_text("\n".join(out) + "\n")
    print("\nWrote docs/API_NOTES.md")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write-notes", action="store_true")
    args = ap.parse_args()
    try:
        ts, se = probe_typesafe(), probe_senso()
    except httpx.HTTPError as exc:
        print("Network error:", type(exc).__name__)
        return 1
    show(ts, se)
    if args.write_notes:
        write_notes(ts, se)
    return 0 if ts["ok"] and se["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
